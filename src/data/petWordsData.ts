for (const w of WORDS) {
  if (_byId.has(w.id)) {
    const existing = _byId.get(w.id)!;
    existing.topics = Array.from(new Set([...existing.topics, ...w.topics])) as Topic[];
  } else {
    _byId.set(w.id, { ...w, topics: [...w.topics] });
  }
}
